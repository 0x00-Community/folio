// The TypeScript side of the wasm boundary. Loads rdocx-bridge, parses Imported into the model, builds Patch from the
// model, caches looks, serves image URLs. The only module that imports the generated wire types; nothing it returns
// is a wire type.
import type { Doc, MediaKey, RunLook, ParaLook, StyleId, Block, BlockSrc } from './model'
import type { MediaRef } from './editor/edit'
import type * as wire from '../engine/bindings/wire' // generated by ts-rs from engine/src/wire.rs

export class OpenError extends Error {
  /** Shown to the user, localized by the app: 'notDocx' | 'encrypted' | 'corrupt' | 'tooLarge'. */
  constructor(readonly reason: 'notDocx' | 'encrypted' | 'corrupt' | 'tooLarge', detail: string) {
    super(detail)
  }
}

/** The written document did not re-import to the model, or lost unmodeled items. Nothing was written to disk. */
export class SaveVerifyError extends Error {
  constructor(readonly firstDifference: string) {
    super(firstDifference)
  }
}

export interface Engine {
  /** Parses a .docx. Throws OpenError. About 13 ms for a small document plus the import walk (measured in grounding). */
  open(bytes: Uint8Array): Opened
  /** A new document: rdocx's Document::new() imported the same way, so New and Open share one code path. */
  blank(): Opened
}

export interface Opened {
  readonly doc: Doc
  readonly source: Source
}

/** One rdocx session: the pristine document as opened, plus fonts and media added this session. */
export interface Source {
  /** Writes the model onto a fresh copy of the pristine document and returns verified .docx bytes. Pure: the same doc always writes the same content. */
  save(doc: Doc): Uint8Array
  /** Same write, then to_pdf_with_fonts with the fonts added so far. */
  exportPdf(doc: Doc): Uint8Array
  exportHtml(doc: Doc): string
  /** Families the document's looks name, for the font service. */
  fontsUsed(doc: Doc): readonly string[]
  addFont(family: string, bytes: Uint8Array): void
  /** Keeps the image bytes in the session (every later save embeds them again) and reads its natural size. */
  addMedia(file: Blob): Promise<MediaRef>
  /** A blob: URL, created on first use from image_data(rel_id) or the added bytes. */
  imageUrl(key: MediaKey): string
  /** rdocx's resolved look for a (paragraph style, character style) pair. Synchronous wasm call, cached in a Map. */
  look(paraStyle: StyleId, charStyle: StyleId | null): RunLook
  paraLook(style: StyleId): ParaLook
  free(): void
}

